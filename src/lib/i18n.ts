const DICTS: Record<Lang, Partial<Dict>> = { en, hi, ta, te };

/** Narrow any string (cookie, localStorage, header) to a supported language; defaults to English. */
export function normalizeLang(value: string | null | undefined): Lang {
  const v = (value || "").trim().toLowerCase().slice(0, 2);
  return LANGS.some((l) => l.code === v) ? (v as Lang) : "en";
}

/** Translate a key, filling {placeholders}; missing keys fall back to English. */
export function t(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  const raw: string = DICTS[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Every key of the English dictionary (the source of truth). */
export const MESSAGE_KEYS = Object.keys(en) as MsgKey[];

/** Keys a language has not translated yet (they show in English). */
export function missingKeys(lang: Lang): MsgKey[] {
  return MESSAGE_KEYS.filter((k) => !(k in DICTS[lang]));
}
